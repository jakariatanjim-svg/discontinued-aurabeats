/**
 * Generates public/_redirects (Cloudflare Pages SPA fallback) from the single
 * source of truth: src/config/routes.ts. Runs automatically before `vite build`.
 * One-line fallback covers every route — and any future route added to that
 * config is covered as soon as `npm run build` runs again. Never hand-edit.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const src = readFileSync(resolve(root, "src/config/routes.ts"), "utf8");
const arr = src.match(/CLEAN_PATHS[^=]*=\s*\[([\s\S]*?)\]/)?.[1] ?? "";
const paths = [...arr.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const out = `# AuraBeats — SPA clean-path fallback (AUTO-GENERATED by scripts/gen-redirects.mjs — do not hand-edit)
# All real app sections → the single index.html (History API router rehydrates them)
${paths.join(" ")} /index.html 200
# Catch-all fallback for any other in-app route (pattern routes like /playlist/<id>)
/* /index.html 200
`;

mkdirSync(resolve(root, "public"), { recursive: true });
writeFileSync(resolve(root, "public/_redirects"), out);
console.log(`[gen-redirects] ${paths.length} section paths + catch-all → public/_redirects`);
